const messages: Record<AppSettings['locale'], Record<RunTranslationKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export function translateRun(
  locale: AppSettings['locale'],
  key: RunTranslationKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function useRunTranslation(): {
  readonly locale: AppSettings['locale'];
  readonly t: (
    key: RunTranslationKey,
    values?: Readonly<Record<string, string | number>>,
  ) => string;
} {
  const locale = useAppSettingsStore((state) => state.settings.locale);
  return { locale, t: (key, values) => translateRun(locale, key, values) };
}
