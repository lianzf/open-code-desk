const messages: Record<AppSettings['locale'], Record<DebugTranslationKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export function translateDebug(
  locale: AppSettings['locale'],
  key: DebugTranslationKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function useDebugTranslation(): {
  readonly locale: AppSettings['locale'];
  readonly t: (
    key: DebugTranslationKey,
    values?: Readonly<Record<string, string | number>>,
  ) => string;
} {
  const locale = useAppSettingsStore((state) => state.settings.locale);
  return { locale, t: (key, values) => translateDebug(locale, key, values) };
}
